"""Subset the installed Noto bundle for BOX-3 labels; never change vendor assets."""

import argparse
import base64
import hashlib
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / "main/boards/espressif/esp32-s3-box-3"


def generate(fonts, extra_text=""):
    spec = importlib.util.spec_from_file_location("glyph_provider", fonts / "scripts/glyph_provider.py")
    provider = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(provider)
    source = fonts / "cbin/font_noto_sans_common_20_4.bin"
    font = provider.CbinFont.from_file(source)
    font.assert_wire_compatible()
    labels = "".join(path.read_text() for path in
                     (BOARD / "box3_display.h", BOARD / "box3_robot.h", ROOT / "main/ez/ez_device.cc"))
    labels += extra_text
    points = sorted(set(range(32, 127)) | {ord(c) for c in labels if ord(c) >= 128})
    assert points[-1] - points[0] < 65536
    bitmap = bytearray()
    descriptors = ["    {0},"]
    for point in points:
        glyph = font.glyph(point)
        assert glyph is not None, f"missing glyph U+{point:04X}"
        descriptors.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}," % (
            len(bitmap), glyph["adv_w"], glyph["box_w"], glyph["box_h"], glyph["ofs_x"], glyph["ofs_y"]))
        bitmap.extend(base64.b64decode(glyph["bitmap"]))
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i+16]) + "," for i in range(0, len(bitmap), 16)]
    return f'''// Generated by scripts/build_box3_ui_font.py from 78/xiaozhi-fonts 2.0.0.
// Source SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}
// Noto glyphs: SIL Open Font License; see box3_ui_font-OFL.txt.
#include <lvgl.h>

static const uint8_t bitmap[] = {{
{chr(10).join(rows)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{
{chr(10).join(descriptors)}
}};
static const uint16_t unicode[] = {{ {', '.join(str(p - points[0]) for p in points)} }};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{{{
    .range_start = {points[0]}, .range_length = {points[-1] - points[0] + 1}, .glyph_id_start = 1,
    .unicode_list = unicode, .glyph_id_ofs_list = nullptr, .list_length = {len(points)},
    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
}}}};
static const lv_font_fmt_txt_dsc_t description = {{
    .glyph_bitmap = bitmap, .glyph_dsc = glyphs, .cmaps = cmaps,
    .kern_dsc = nullptr, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0,
}};
extern const lv_font_t box3_ui_font = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {font.line_height}, .base_line = {font.base_line},
    .dsc = &description,
}};
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fonts-root", type=Path, required=True)
    args = parser.parse_args()
    (BOARD / "box3_ui_font.cc").write_text(generate(args.fonts_root))
