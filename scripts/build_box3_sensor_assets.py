"""Migrate archived factory Sensor Monitor icons to LVGL 9; keep original pixels."""
from pathlib import Path

from build_box3_robot_assets import convert

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/references/esp-box3/sources/esp-box/examples/factory_demo/main/gui/image"
BOARD = ROOT / "main/boards/espressif/esp32-s3-box-3"


def generate():
    chunks = ['// Generated by scripts/build_box3_sensor_assets.py.\n'
              '// Espressif esp-box aae1b7a6 factory_demo icons; Apache-2.0.\n'
              '// See docs/references/esp-box3/sources/esp-box/LICENSE.\n#include <lvgl.h>\n']
    for name in ("temp", "humidity", "rader_on", "rader_off"):
        source = (SOURCE / f"icon_{name}.c").read_text()
        width, height, data = convert(source)
        rows = ["    " + ",".join(f"0x{x:02x}" for x in data[i:i+24]) + ","
                for i in range(0, len(data), 24)]
        chunks.append(f'''static const uint8_t {name}_data[] = {{
{chr(10).join(rows)}
}};
extern const lv_image_dsc_t box3_sensor_{name} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,
               .flags = 0, .w = {width}, .h = {height}, .stride = {width * 4}}},
    .data_size = sizeof({name}_data), .data = {name}_data,
}};
''')
    return "\n".join(chunks)


if __name__ == "__main__":
    (BOARD / "box3_sensor_assets.cc").write_text(generate())
