"""Convert archived Espressif LVGL 8 RGB565+alpha images to LVGL 9 ARGB8888."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / "main/boards/espressif/esp32-s3-box-3"
SOURCE = ROOT / "docs/references/esp-box3/sources/esp-box/examples/chatgpt_demo/main/ui/images"
NAMES = ("setup_bg", "body", "body_shadow", "body_eye_screen", "sleep_body_eyes",
         "sleep_big_z", "sleep_small_z", "listen_back_glow", "listen_body_eyes_1",
         "listen_body_eyes_2", "reply_body", "reply_small_shadow", "reply_chatgpt_bg")


def convert(source):
    width, height = (int(re.search(r"\.header\." + key + r" = (\d+)", source)[1])
                     for key in ("w", "h"))
    raw = re.search(r"\[\] = \{(.*?)\};", source, re.S)[1]
    raw = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", raw))
    assert len(raw) == width * height * 3, "expected RGB565 big-endian plus alpha"
    output = bytearray()
    for high, low, alpha in zip(raw[::3], raw[1::3], raw[2::3]):
        pixel = low | high << 8
        r, g, b = pixel >> 11, (pixel >> 5) & 63, pixel & 31
        output.extend(((b << 3) | (b >> 2), (g << 2) | (g >> 4),
                       (r << 3) | (r >> 2), alpha))
    return width, height, output


def generate():
    chunks = ['// Generated by scripts/build_box3_robot_assets.py.\n'
              '// Espressif esp-box aae1b7a6, chatgpt_demo images; Apache-2.0.\n'
              '// See box3_robot-NOTICE.txt and the archived source/LICENSE.\n#include <lvgl.h>\n']
    for name in NAMES:
        width, height, data = convert((SOURCE / f"ui_img_{name}_png.c").read_text())
        rows = ["    " + ",".join(f"0x{x:02x}" for x in data[i:i+24]) + ","
                for i in range(0, len(data), 24)]
        chunks.append(f'''static const uint8_t {name}_data[] = {{
{chr(10).join(rows)}
}};
extern const lv_image_dsc_t box3_robot_{name} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,
               .flags = 0, .w = {width}, .h = {height}, .stride = {width * 4}}},
    .data_size = sizeof({name}_data), .data = {name}_data,
}};
''')
    return "\n".join(chunks)


if __name__ == "__main__":
    # RGB565 primary colors and alpha byte order must survive the conversion.
    for pixel, bgra in (("0xf8,0x00,0x80", bytes((0, 0, 255, 128))),
                        ("0x07,0xe0,0xff", bytes((0, 255, 0, 255))),
                        ("0x00,0x1f,0x00", bytes((255, 0, 0, 0)))):
        assert convert("x[] = {" + pixel + "}; .header.w = 1; .header.h = 1;")[2] == bgra
    (BOARD / "box3_robot_assets.cc").write_text(generate())
